#!/usr/bin/env python3
"""Bake the room's light on a card's face for every place around the player's seat.

    export.py <work dir> <out.cpp>

Traces (trace.cpp) a large patch of table, 1.2 m across and 1 m deep before the player's
eyes, then writes for each point of a 49 x 41 grid what the room does to a card lying
there, in the one form the table can draw over a card (a premultiplied overlay), in the
screen's own (sRGB) values:

    seen = face x level + gloss

`level` is the light falling on the paper and passing through its varnish, `gloss` (rgb) the
room the varnish mirrors towards the eyes. The eye is taken as adapted to the sunlit paper
(white balance), and the exposure keeps the best-lit paper at the face's own colour, so
`level` is at most 1 and the light never brightens the print.
"""
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bake  # noqa: E402  (the shared room constants and tracer driver)

WIDTH, DEPTH, NX, NY = 1.2, 1.0, 49, 41
EYE_BACK, EYE_UP = .30, .42  # as trace.cpp's eye()


def main():
    work, out_path = sys.argv[1:3]
    os.makedirs(work, exist_ok=True)
    tracer = os.path.join(work, "trace")
    subprocess.run(["clang++", "-std=c++20", "-O3", "-o", tracer,
                    os.path.join(HERE, "trace.cpp")], check=True)
    cells = bake.run_parts(tracer, "cells", WIDTH, DEPTH, NX, NY, 8,
                           os.path.join(work, "cells.f32")).reshape(NY, NX, -1)
    coat = bake.run_parts(tracer, "coat", WIDTH, DEPTH, NX, NY, 16384,
                          os.path.join(work, "coat.f32")).reshape(NY, NX, 3).astype(float)
    bins = cells[..., :-1].reshape(NY, NX, 64, 16, 3).astype(float)
    sun_seen = cells[..., -1].astype(float)

    band_cos = np.sqrt(1 - (np.arange(16) + .5) / 16)
    rest_coat = (bins * (np.pi / 1024) *
                 (1 - bake.fresnel(band_cos))[None, None, None, :, None]).sum((2, 3))
    sun_up = np.sin(bake.SUN_UP)
    e_sun = sun_seen[..., None] * bake.SUN_LIGHT * sun_up
    xs = np.linspace(0, WIDTH, NX)
    ys = np.linspace(0, DEPTH, NY)
    vx = WIDTH / 2 - xs[None, :]
    vy = DEPTH + EYE_BACK - ys[:, None]
    nv = EYE_UP / np.sqrt(vx ** 2 + vy ** 2 + EYE_UP ** 2)
    paper = ((e_sun * (1 - bake.fresnel(sun_up)) + rest_coat) *
             (1 - bake.fresnel(nv))[..., None] / np.pi)

    # Adapted to the paper half a metre before the eyes; exposed so the best-lit paper
    # anywhere a window can show is the face's own colour.
    reference = paper[int(round((DEPTH - .5) / DEPTH * (NY - 1))), NX // 2]
    light = paper / reference
    gloss_light = coat / reference
    brightest = light.mean(-1).max()
    light /= brightest
    gloss_light /= brightest

    # The screen blends in its own (sRGB) values, not in light, so fit there: one shared
    # multiplier and a gloss per channel, matching both white paper and black ink.
    white, black = .86, .037
    white_s, black_s = (bake.linear_to_srgb(np.array(v)) / 255 for v in (white, black))
    seen_white = bake.linear_to_srgb(white * light + gloss_light) / 255
    seen_black = bake.linear_to_srgb(black * light + gloss_light) / 255
    level = np.clip(((seen_white - seen_black) / (white_s - black_s)).mean(-1), 0, 1)
    gloss = np.clip(((seen_white - level[..., None] * white_s) +
                     (seen_black - level[..., None] * black_s)) / 2, 0, 1)

    with open(out_path, "w") as out:
        out.write("// GENERATED by authoring/table_light/export.py - do not edit by hand.\n")
        out.write("// The sunlit room's light on a card's face around the player's seat: see\n")
        out.write("// table_light.hpp. Regenerate (a few minutes):\n")
        out.write("//   python3 authoring/table_light/export.py <work dir> "
                  "shared/cards/table_light_bake.cpp\n")
        out.write(f"// level {level.min():.4f}..{level.max():.4f}, "
                  f"gloss {gloss.min():.4f}..{gloss.max():.4f}\n")
        out.write('#include "table_light.hpp"\n\nnamespace games::detail {\n\n')
        def rows(name, values, per_line):
            out.write(f"const float {name}[{NY * NX * values[0].size // NX}] = {{\n")
            flat = [f"{v:.4f}f" for v in np.asarray(values).reshape(-1)]
            for i in range(0, len(flat), per_line):
                out.write("    " + ", ".join(flat[i:i + per_line]) + ",\n")
            out.write("};\n\n")
        rows("light_level", level, 10)
        rows("light_gloss", gloss, 9)
        out.write("}  // namespace games::detail\n")
    print(f"level {level.min():.4f}..{level.max():.4f}  gloss mean {gloss.mean(axis=(0, 1))}")


if __name__ == "__main__":
    main()
